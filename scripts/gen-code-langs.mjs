#!/usr/bin/env node
/**
 * V28: build the lazily-loaded multi-language code documents from REAL source files.
 *
 *   src/codeCatalog/<algo>/langs/meta.json   { algo, idPrefix, titleBase, files: { python, cpp, java, rust, go } }
 *   src/codeCatalog/<algo>/langs/<file>      complete reference implementation in that language
 *
 * Anchors are written ON the statement they name, as a trailing marker comment:
 *     dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])  # @a: dpFill
 *     len++;  // @a: lpsExtend+1          (range = this line + 1 following line)
 *     j--;    // @a: reconstructUp, foo   (several semantic ids on one statement)
 * The marker is stripped from the displayed source; line numbers are those of the displayed
 * document itself (never copied from another language). Output:
 *   src/codeCatalog/<algo>/langs.generated.ts   (one dynamic-import chunk per algorithm)
 *
 * Usage: node scripts/gen-code-langs.mjs [--check]
 *   --check  exit 1 if any generated file is stale (used by tests too, via buildAll()).
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = join(ROOT, 'src', 'codeCatalog')

export const LANGS = ['python', 'cpp', 'java', 'rust', 'go']
export const LANG_LABEL = { python: 'Python', cpp: 'C++', java: 'Java', rust: 'Rust', go: 'Go' }
const EXT = { python: 'py', cpp: 'cpp', java: 'java', rust: 'rs', go: 'go' }
const MARKER = {
  python: /\s*#\s*@a:\s*([^#]*?)\s*$/,
  cpp: /\s*\/\/\s*@a:\s*(.*?)\s*$/,
  java: /\s*\/\/\s*@a:\s*(.*?)\s*$/,
  rust: /\s*\/\/\s*@a:\s*(.*?)\s*$/,
  go: /\s*\/\/\s*@a:\s*(.*?)\s*$/,
}

export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}

/** Strip markers → { source, anchors } (1-based inclusive line ranges). */
export function parseAnnotated(raw, lang, where = '') {
  const re = MARKER[lang]
  if (!re) throw new Error(`unknown language ${lang}`)
  const text = raw.replace(/\r\n/g, '\n').replace(/\n+$/, '')
  const out = []
  const anchors = []
  const seen = new Set()
  text.split('\n').forEach((line, idx) => {
    const m = line.match(re)
    if (!m) {
      if (/@a:/.test(line)) throw new Error(`${where}:${idx + 1}: malformed anchor marker`)
      out.push(line.replace(/\s+$/, ''))
      return
    }
    const body = line.slice(0, m.index).replace(/\s+$/, '')
    if (!body.trim()) throw new Error(`${where}:${idx + 1}: anchor marker on an empty line`)
    out.push(body)
    for (const spec of m[1].split(',').map((s) => s.trim()).filter(Boolean)) {
      const sm = spec.match(/^([A-Za-z_][\w]*)(?:\+(\d+))?$/)
      if (!sm) throw new Error(`${where}:${idx + 1}: bad anchor spec "${spec}"`)
      if (seen.has(sm[1])) throw new Error(`${where}:${idx + 1}: duplicate anchor "${sm[1]}"`)
      seen.add(sm[1])
      anchors.push({ id: sm[1], range: { startLine: idx + 1, endLine: idx + 1 + Number(sm[2] ?? 0) } })
    }
  })
  const source = out.join('\n') + '\n'
  const nLines = out.length
  for (const a of anchors) {
    if (a.range.endLine > nLines) throw new Error(`${where}: anchor ${a.id} range ends past the document`)
  }
  return { source, anchors }
}

export function algoDirs() {
  return readdirSync(CATALOG, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(CATALOG, d.name, 'langs', 'meta.json')))
    .map((d) => d.name)
    .sort()
}

/** Build the documents for one catalog dir (pure: reads files, returns data). */
export function buildDocs(dir) {
  const langDir = join(CATALOG, dir, 'langs')
  const meta = JSON.parse(readFileSync(join(langDir, 'meta.json'), 'utf8'))
  const docs = []
  for (const lang of LANGS) {
    const file = meta.files?.[lang]
    if (!file) throw new Error(`${dir}: meta.json lacks ${lang}`)
    const raw = readFileSync(join(langDir, file), 'utf8')
    const { source, anchors } = parseAnnotated(raw, lang, `${dir}/langs/${file}`)
    docs.push({
      documentId: `${meta.idPrefix}.${EXT[lang]}`,
      language: lang,
      title: `${meta.titleBase} (${LANG_LABEL[lang]})`,
      sourceFile: `src/codeCatalog/${dir}/langs/${file}`,
      source,
      sourceHash: sha256(source),
      anchors,
    })
  }
  return { algo: meta.algo, dir, docs }
}

export function renderModule(built) {
  const body = JSON.stringify(built.docs, null, 2)
  return `// AUTO-GENERATED by scripts/gen-code-langs.mjs from src/codeCatalog/${built.dir}/langs/* — do not edit.
// Each document's line numbers are its own (anchors were written on the statements themselves).
import type { GeneratedLangDoc } from '../languages'

const docs: GeneratedLangDoc[] = ${body}

export default docs
`
}

export function buildAll() {
  return algoDirs().map((dir) => {
    const built = buildDocs(dir)
    return { ...built, path: join(CATALOG, dir, 'langs.generated.ts'), text: renderModule(built) }
  })
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const b of buildAll()) {
    const cur = existsSync(b.path) ? readFileSync(b.path, 'utf8') : ''
    if (cur === b.text) continue
    if (check) {
      console.error(`stale: ${b.path}`)
      stale++
    } else {
      writeFileSync(b.path, b.text)
      console.log(`wrote ${b.path} (${b.docs.length} docs)`)
    }
  }
  if (check && stale) process.exit(1)
}
