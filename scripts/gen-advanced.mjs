#!/usr/bin/env node
/**
 * 高阶算法 generator (single source of truth = real source files; nothing hand-copied):
 *
 *   src/codeCatalog/<id>/langs/{meta.json,<ts file>.ts.txt,*.py,*.cpp,...}   six-language teaching docs
 *        → src/codeCatalog/<id>/index.ts            (TypeScript CodeDocument; other five via gen-code-langs.mjs)
 *   src/features/advanced/sources/<id>/{<id>.cpp,meta.json}                 C++-only STL teaching docs
 *        → src/codeCatalog/<id>/index.ts
 *   src/features/advanced/sources/<id>/{contest.cpp,contest.main.cpp}      contest variant (core / core+main)
 *        → src/features/advanced/templates/sources.generated.ts   (lazy chunk)
 *   hashes of every displayed source
 *        → src/features/advanced/templates/hashes.generated.ts    (eager, tiny)
 *
 * Usage: node scripts/gen-advanced.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseAnnotated, sha256, buildDocs } from './gen-code-langs.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CAT = join(ROOT, 'src', 'codeCatalog')
const SRC = join(ROOT, 'src', 'features', 'advanced', 'sources')
const TPL = join(ROOT, 'src', 'features', 'advanced', 'templates')

export const SIX = ['dsu', 'fenwick', 'segtree', 'segtree_lazy', 'prefix_diff', 'discretize', 'bs_answer', 'mono_stack', 'mono_queue', 'topo', 'lca', 'lis', 'number_theory']
export const CPP_ONLY = ['stl_bounds', 'stl_priority_queue', 'stl_vector']
export const TESTSET_VERSION = 'adv-tests-v1'

const pascal = (id) => id.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase())

function tsDocText(id, language, title, source, hash, anchors, labels) {
  const items = anchors.map((a) => ({ id: a.id, label: labels[a.id] ?? a.id, range: a.range }))
  return `// AUTO-GENERATED by scripts/gen-advanced.mjs — do not edit.
import type { CodeDocument } from '../types'

const SOURCE = ${JSON.stringify(source)}

export const ${id.toUpperCase()}_HASH = ${JSON.stringify(hash)}

export function get${pascal(id)}Catalog(): { typescript: CodeDocument; pseudocode?: CodeDocument } {
  const typescript: CodeDocument = {
    documentId: ${JSON.stringify(`${id.replace(/_/g, '_')}.${language === 'cpp' ? 'cpp' : 'ts'}`)},
    language: ${JSON.stringify(language)},
    title: ${JSON.stringify(title)},
    source: SOURCE,
    sourceHash: ${JSON.stringify(hash)},
    anchors: ${JSON.stringify(items, null, 2).replace(/\n/g, '\n    ')},
  }
  return { typescript }
}
`
}

export function buildAdvanced() {
  const files = []
  const hashes = {}
  const contest = {}
  // six-language topics: TS document + hashes of all six
  for (const id of SIX) {
    const meta = JSON.parse(readFileSync(join(CAT, id, 'langs', 'meta.json'), 'utf8'))
    const raw = readFileSync(join(CAT, id, 'langs', meta.ts), 'utf8')
    const { source, anchors } = parseAnnotated(raw, 'cpp', `${id}/${meta.ts}`)
    const hash = sha256(source)
    files.push({ path: join(CAT, id, 'index.ts'), text: tsDocText(id, 'typescript', `${meta.titleBase} (TypeScript)`, source, hash, anchors, meta.labels) })
    const built = buildDocs(id)
    hashes[id] = { teach: { typescript: hash, ...Object.fromEntries(built.docs.map((d) => [d.language, d.sourceHash])) } }
  }
  for (const id of CPP_ONLY) {
    const meta = JSON.parse(readFileSync(join(SRC, id, 'meta.json'), 'utf8'))
    const raw = readFileSync(join(SRC, id, meta.file), 'utf8')
    const { source, anchors } = parseAnnotated(raw, 'cpp', `${id}/${meta.file}`)
    const hash = sha256(source)
    files.push({ path: join(CAT, id, 'index.ts'), text: tsDocText(id, 'cpp', meta.title, source, hash, anchors, meta.labels) })
    hashes[id] = { teach: { cpp: hash } }
  }
  for (const id of [...SIX, ...CPP_ONLY]) {
    const core = readFileSync(join(SRC, id, 'contest.cpp'), 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '') + '\n'
    const main = readFileSync(join(SRC, id, 'contest.main.cpp'), 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '') + '\n'
    const full = core + main
    contest[id] = { core: { source: core, hash: sha256(core) }, full: { source: full, hash: sha256(full) } }
    hashes[id] = { ...(hashes[id] ?? {}), contest: { core: sha256(core), full: sha256(full) } }
  }
  // public keys = template/topic ids (hyphenated), the same ids the UI and routes use
  const rekey = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k.replace(/_/g, '-'), v]))
  const hashesPub = rekey(hashes)
  const contestPub = rekey(contest)
  files.push({
    path: join(TPL, 'sources.generated.ts'),
    text: `// AUTO-GENERATED by scripts/gen-advanced.mjs from src/features/advanced/sources/** — do not edit.
export interface ContestSource { core: { source: string; hash: string }; full: { source: string; hash: string } }
const sources: Record<string, ContestSource> = ${JSON.stringify(contestPub, null, 2)}
export default sources
`,
  })
  files.push({
    path: join(TPL, 'hashes.generated.ts'),
    text: `// AUTO-GENERATED by scripts/gen-advanced.mjs — SHA-256 of every displayed template source.
export const TESTSET_VERSION = ${JSON.stringify(TESTSET_VERSION)}
export const SOURCE_HASHES: Record<string, { teach?: Record<string, string>; contest?: { core: string; full: string } }> = ${JSON.stringify(hashesPub, null, 2)}
`,
  })
  return files
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const f of buildAdvanced()) {
    const cur = existsSync(f.path) ? readFileSync(f.path, 'utf8') : ''
    if (cur === f.text) continue
    if (check) {
      console.error(`stale: ${f.path}`)
      stale++
    } else {
      mkdirSync(dirname(f.path), { recursive: true })
      writeFileSync(f.path, f.text)
      console.log(`wrote ${f.path}`)
    }
  }
  if (check && stale) process.exit(1)
}
